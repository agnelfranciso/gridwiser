export function getPresetTemplate(id: PresetTemplateId | string): PresetTemplate {
  return PRESET_TEMPLATES.find((t) => t.id === id) ?? PRESET_TEMPLATES[0];
}

export function getTemplateFontCss(family: TemplateFontFamily): string {
  switch (family) {
    case 'geist':
      return 'var(--font-geist), sans-serif';
    case 'plus-jakarta':
      return 'var(--font-plus-jakarta), sans-serif';
    case 'space-grotesk':
      return 'var(--font-space-grotesk), sans-serif';
    case 'dm-sans':
      return 'var(--font-dm-sans), sans-serif';
    case 'newsreader':
      return 'var(--font-newsreader), Georgia, serif';
    case 'syne':
      return 'var(--font-syne), sans-serif';
    case 'outfit':
      return 'var(--font-outfit), sans-serif';
    case 'jetbrains-mono':
      return 'var(--font-jetbrains-mono), monospace';
    default:
      return 'var(--font-inter), sans-serif';
  }
}

export function getTemplateMonoCss(family: PresetTemplate['monoFamily']): string {
  return family === 'jetbrains-mono'
    ? 'var(--font-jetbrains-mono), monospace'
    : 'var(--font-ibm-plex-mono), monospace';
}
